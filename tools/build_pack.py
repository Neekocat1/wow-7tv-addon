#!/usr/bin/env python3
"""Bake emotes directly into the SevenTVEmotes addon (no helper needed to see them).

Use this for a pre-built release, e.g. shipping 7TV's global emotes inside the addon on
CurseForge. Players' own additions still go through the helper.

  python tools/build_pack.py                         # 7TV global set
  python tools/build_pack.py --twitch xqc --no-global
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "helper"))

from seventv_helper import images, seventv  # noqa: E402
from seventv_helper.luasv import lua_str  # noqa: E402
from seventv_helper.library import NAME_RE  # noqa: E402


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--twitch", action="append", default=[])
    p.add_argument("--set", action="append", default=[])
    p.add_argument("--no-global", action="store_true")
    p.add_argument("--addon-dir", type=Path, default=ROOT / "addon" / "SevenTVEmotes")
    p.add_argument("--cache-dir", type=Path, default=ROOT / "tools" / ".cache")
    args = p.parse_args(argv)

    emotes: dict[str, seventv.Emote] = {}
    if not args.no_global:
        for e in seventv.fetch_global():
            emotes[e.name] = e
    for login in args.twitch:
        for e in seventv.fetch_twitch_channel(login)[1]:
            emotes[e.name] = e
    for sid in args.set:
        for e in seventv.fetch_set(seventv.parse_ref(sid)[1] if "/" in sid else sid)[1]:
            emotes[e.name] = e
    emotes = {n: e for n, e in emotes.items() if NAME_RE.match(n)}

    out_dir = args.addon_dir / "emotes"
    out_dir.mkdir(parents=True, exist_ok=True)
    info: dict[str, dict] = {}
    for e in {e.id: e for e in emotes.values()}.values():
        try:
            src = images.download(e, 64, args.cache_dir)
            info[e.id] = images.render(src, out_dir / f"{e.id}.tga")
        except Exception as ex:  # keep going
            print(f"  ! {e.name}: {ex}", file=sys.stderr)

    lines = ["-- Generated by tools/build_pack.py. Re-run it instead of editing.",
             "local _, ns = ...",
             "-- [name] = { file, width, height, texWidth, texHeight, 7tvId [, frames, columns, msPerFrame] }",
             "ns.EmoteData = {"]
    for name, e in sorted(emotes.items(), key=lambda kv: kv[0].lower()):
        i = info.get(e.id)
        if not i:
            continue
        vals = [lua_str("emotes\\" + e.id + ".tga"), i["w"], i["h"], i["tw"], i["th"], lua_str(e.id)]
        if i["frames"] > 1:
            vals += [i["frames"], i["cols"], i["ms"]]
        lines.append("  [%s] = { %s }," % (lua_str(name), ", ".join(map(str, vals))))
    lines.append("}")
    (args.addon_dir / "Emotes.lua").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"Baked {len(info)} textures / {len(emotes)} names into {args.addon_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
